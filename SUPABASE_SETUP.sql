-- Redline Horizon global leaderboard
-- Run this once in Supabase SQL Editor.

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null check (char_length(player_name) between 1 and 24),
  score bigint not null check (score >= 0),
  distance numeric(10,2) not null default 0 check (distance >= 0),
  top_speed integer not null default 0 check (top_speed >= 0),
  near_misses integer not null default 0 check (near_misses >= 0),
  created_at timestamptz not null default now()
);

alter table public.leaderboard enable row level security;

drop policy if exists "Public can read leaderboard" on public.leaderboard;
create policy "Public can read leaderboard"
on public.leaderboard
for select
to anon, authenticated
using (true);

drop policy if exists "Public can submit leaderboard scores" on public.leaderboard;
create policy "Public can submit leaderboard scores"
on public.leaderboard
for insert
to anon, authenticated
with check (
  char_length(player_name) between 1 and 24
  and score >= 0
  and distance >= 0
  and top_speed >= 0
  and near_misses >= 0
);

create index if not exists leaderboard_score_idx
on public.leaderboard (score desc, created_at asc);
